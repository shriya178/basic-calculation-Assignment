"use strict";
let num = 600;
if (num >= 1 && num <= 100) {
    console.log('Number is between 1 and 100');
}
else if (num >= 101 && num <= 500) {
    console.log('Number is between 101 and 500');
}
else if (num > 500) {
    console.log('Number is above 500');
}
else {
    console.log('Invalid Number');
}
